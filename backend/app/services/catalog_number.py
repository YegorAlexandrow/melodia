"""Нормализация каталожных номеров «Мелодии».

Каталожные номера на Discogs отформатированы неряшливо: разные тире (—, –, -),
пробелы, регистр, иногда латиница вместо кириллицы в префиксе (C вместо С).
Чтобы поиск и хранение были устойчивы, приводим номер к канонической форме:

    "С60—07271-2"   -> "С6007271 2"  ? нет — убираем разделители целиком
    "С60 07271 2"   -> "С6007271·2"

Стратегия: верхний регистр, унификация лукэлайков латиница→кириллица в типичных
префиксах, удаление всех разделителей (пробелы/тире/слэши) → только буквы и цифры.
Так "С60—07271-2", "С60 07271 2" и "C60 07271 2" дают одинаковый ключ.
"""

from __future__ import annotations

import re

# Латинские буквы, которыми на Discogs часто подменяют кириллические префиксы
# «Мелодии» (С, Д, Г, М, А, Н, Т, В, Р, Е, К, О, Х, …). Маппим в кириллицу.
_LOOKALIKE_LAT_TO_CYR = str.maketrans(
    {
        "C": "С",
        "D": "Д",  # латинской D-кириллицы нет, но префикс «Д» иногда пишут латиницей
        "M": "М",
        "A": "А",
        "H": "Н",
        "T": "Т",
        "B": "В",
        "P": "Р",
        "E": "Е",
        "K": "К",
        "O": "О",
        "X": "Х",
    }
)

# всё, что не буква и не цифра (любой алфавит) — разделитель
_SEP_RE = re.compile(r"[^0-9A-Za-zА-Яа-яЁё]+")


def normalize_catalog_number(raw: str | None) -> str:
    """Привести каталожный номер к каноническому виду для поиска/хранения.

    Пустая/None строка → "". Регистронезависимо, без разделителей.
    """

    if not raw:
        return ""
    s = raw.strip().upper()
    s = s.translate(_LOOKALIKE_LAT_TO_CYR)
    s = _SEP_RE.sub("", s)
    return s


def catalog_prefix(raw: str | None) -> str | None:
    """Выделить буквенный префикс (Д / С / СМ / Г …) из каталожного номера.

    Берём ведущие буквы (и цифры, приклеенные к буквам, как «С60») до первого
    разделителя/группы цифр-после-пробела. Возвращает None, если префикса нет.
    """

    if not raw:
        return None
    s = raw.strip().upper().translate(_LOOKALIKE_LAT_TO_CYR)
    m = re.match(r"^([А-ЯЁA-Z]+\d*)", s)
    if not m:
        return None
    return m.group(1)
